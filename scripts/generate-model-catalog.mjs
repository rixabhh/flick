import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = JSON.parse(fs.readFileSync(path.join(root, 'src-tauri/resources/speech-catalog.json'), 'utf8'));
const legacy = JSON.parse(fs.readFileSync(path.join(root, 'src-tauri/resources/legacy-models.json'), 'utf8'));
// Architecture names implemented by our pinned transcribe-cpp 0.2.0 registry.
const architectures = new Set(['whisper', 'parakeet', 'canary', 'canary_qwen', 'cohere_asr', 'qwen3_asr', 'moss', 'voxtral', 'voxtral_realtime', 'moonshine', 'moonshine_streaming', 'sensevoice', 'funasr_nano', 'gigaam', 'granite_speech', 'granite_speech_nar', 'medasr']);
const familyName = (value = 'compatible') => ({ qwen3_asr: 'Qwen3 ASR', sensevoice: 'SenseVoice', funasr_nano: 'FunASR', canary_qwen: 'Canary Qwen' })[value] || value.replaceAll('_', ' ').replace(/\b\w/g, (letter) => letter.toUpperCase());

export function buildCatalog() {
  const result = [];
  const used = new Set();
  for (const entry of legacy) {
    const descriptor = source.models.find((model) => model.files.some((file) => file.filename === entry.file_name));
    const whisper = entry.id.startsWith('whisper-');
    const languages = descriptor?.languages || (entry.english_only ? ['en'] : []);
    result.push({ ...entry, group: descriptor?.name || entry.name, quant: descriptor ? 'Q8_0' : 'F16',
      engine: whisper ? 'Whisper / GGML' : `${familyName(descriptor?.family)} / GGUF`,
      supported_languages: languages, supports_translation: whisper ? !entry.english_only : Boolean(descriptor?.capabilities.translate),
      supports_language_detection: whisper ? !entry.english_only : Boolean(descriptor?.capabilities.lang_detect),
      recommended: true, license: descriptor?.license || 'mit', source_url: descriptor ? `https://huggingface.co/${descriptor.id}` : 'https://huggingface.co/ggerganov/whisper.cpp' });
    used.add(entry.file_name);
  }
  for (const model of source.models) {
    if (!architectures.has(model.architecture)) throw new Error(`Unsupported architecture: ${model.architecture}`);
    if (!/^[a-f0-9]{40}$/.test(model.revision)) throw new Error(`Unpinned repository: ${model.id}`);
    for (const file of model.files) {
      // Multi-file diarization bundles need a separate acquisition contract;
      // never present one component as a complete downloadable model.
      if (file.filename.includes('/')) continue;
      if (used.has(file.filename)) continue;
      if (!/^[a-f0-9]{64}$/.test(file.sha256) || file.size_bytes < 1_000_000 || /[/\\]/.test(file.filename)) throw new Error(`Invalid model file: ${file.filename}`);
      used.add(file.filename);
      result.push({ id: `${model.slug.toLowerCase()}-${file.quant.toLowerCase()}`, name: `${model.name} · ${file.quant}`, group: model.name, quant: file.quant,
        description: `${model.description}. ${file.quant.startsWith('Q') ? 'Quantized for a smaller download.' : 'Full precision; higher memory requirements.'}`,
        language: model.languages.length === 1 ? model.languages[0].toUpperCase() : `${model.languages.length} languages`,
        file_name: file.filename, url: `https://huggingface.co/${model.id}/resolve/${model.revision}/${file.filename}?download=true`,
        sha256: file.sha256, size_bytes: file.size_bytes, english_only: model.languages.length === 1 && model.languages[0] === 'en',
        engine: `${familyName(model.family)} / GGUF`, supported_languages: model.languages,
        supports_translation: model.capabilities.translate, supports_language_detection: model.capabilities.lang_detect,
        recommended: file.quant === model.default_quant, license: model.license, source_url: `https://huggingface.co/${model.id}` });
    }
  }
  if (new Set(result.map((model) => model.id)).size !== result.length) throw new Error('Duplicate catalog ID');
  return result;
}

const quote = (value) => JSON.stringify(value);
export function renderCatalog() {
  return '// Generated by scripts/generate-model-catalog.mjs. Do not edit by hand.\n&[\n' + buildCatalog().map((model) => '    CatalogModel {\n' + Object.entries(model).map(([key, value]) => `        ${key}: ${Array.isArray(value) ? '&[' + value.map(quote).join(', ') + ']' : typeof value === 'string' ? quote(value) : value},`).join('\n') + '\n    },').join('\n') + '\n]\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = path.join(root, 'src-tauri/src/model_catalog.rs');
  const rendered = renderCatalog();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== rendered) throw new Error('Model catalog needs regeneration');
  } else fs.writeFileSync(target, rendered);
  console.log(`Catalog: ${buildCatalog().length} pinned local artifacts`);
}
